"""Ask the open engine which words it refuses as DAX variable names -> config/dax_reserved_words.txt (model_gate rule C6).

    py tools/sync_dax_reserved.py [<PBIDesktop PID>]     (default: the first open Power BI Desktop)

Microsoft's published keyword list is incomplete for current engines (TOP, WORK, ON, KEY broke measures of this kit), so the
list is measured, not typed: every function name the engine lists ($SYSTEM.MDSCHEMA_FUNCTIONS), the DAX statement keywords,
common short words and every VAR name of the generated model are tried as  EVALUATE ROW("x", VAR <w> = 1 RETURN <w>);
a syntax error = reserved. Re-run after a Power BI Desktop update (new DAX features add keywords).
"""
import json
import re
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent
OUT = ROOT / "config" / "dax_reserved_words.txt"
SCRATCH = ROOT.parent / "_uitest"
COMMON = """
define evaluate order by start at asc desc measure column table function var return true false not and or in is null blank
calendar week weeks quarter year month day days hour hours minute minutes second seconds date time datetime today now
key keys top bottom work on off as to from with join left right inner outer full cross union set type data text number int
integer string double single boolean currency decimal variant numeric scalar expr val anyval anyref int64 none both create
value values filter rank order index row rows first last next prev previous current all any some each every partitionby
orderby matchby window offset skip dense keep blanks default relative absolute min max sum count avg total ratio share pct
share base target plan actual status color label flag mode level area zone site code name id ref span from_ until till
case when then else end select where group having distinct limit top_n new old cur lag lead sort asc_ desc_ include exclude
""".split()


def pid_arg():
    if len(sys.argv) > 1:
        return int(sys.argv[1])
    p = subprocess.run(["powershell.exe", "-NoProfile", "-Command", "(Get-Process PBIDesktop -ErrorAction SilentlyContinue | Select-Object -First 1).Id"],
                       capture_output=True, text=True)
    if not p.stdout.strip():
        raise SystemExit("!! no Power BI Desktop is open")
    return int(p.stdout.strip())


def model_var_names():
    names = set()
    for f in (ROOT / "dist").glob("*/*.SemanticModel/definition/**/*.tmdl"):
        names |= {m.lower() for m in re.findall(r"(?i)\bVAR\s+([A-Za-z_][A-Za-z0-9_]*)\s*=", f.read_text(encoding="utf-8"))}
    return names


def main():
    pid = pid_arg()
    print(f"engine of PBIDesktop {pid}: reading function names ...", flush=True)
    p = subprocess.run(["powershell.exe", "-NoProfile", "-ExecutionPolicy", "Bypass", "-File", str(HERE / "pbi_dax.ps1"), "-ProcId", str(pid),
                        "-Dax", "SELECT FUNCTION_NAME FROM $SYSTEM.MDSCHEMA_FUNCTIONS", "-TimeoutSec", "120"],
                       capture_output=True, text=True, timeout=300)
    rows = json.loads(p.stdout.strip() or "{}")
    if not isinstance(rows, list) or not rows:
        raise SystemExit(f"!! MDSCHEMA_FUNCTIONS failed: {p.stdout[:300]} {p.stderr[:300]}")
    funcs = {str(r["FUNCTION_NAME"]).lower() for r in rows if re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]*", str(r["FUNCTION_NAME"]))}
    used = model_var_names()
    cand = sorted(funcs | set(COMMON) | used)
    print(f"{len(funcs)} function names, {len(used)} VAR names in dist/, {len(cand)} candidates -> probing", flush=True)
    SCRATCH.mkdir(exist_ok=True)
    qf, rf = SCRATCH / "_q_reserved.json", SCRATCH / "_r_reserved.json"
    qf.write_text(json.dumps([{"id": w, "dax": f'EVALUATE ROW("x", VAR {w} = 1 RETURN {w})'} for w in cand]), encoding="utf-8")
    if rf.exists():
        rf.unlink()
    r = subprocess.run(["powershell.exe", "-NoProfile", "-ExecutionPolicy", "Bypass", "-File", str(HERE / "run_dax_batch.ps1"), "-ProcId", str(pid),
                        "-InJson", str(qf), "-OutJson", str(rf), "-TimeoutSec", "30"], timeout=3600)
    if r.returncode != 0 or not rf.exists():
        raise SystemExit(f"!! probe batch failed (exit {r.returncode})")
    res = json.loads(rf.read_text(encoding="utf-8-sig"))
    res = res if isinstance(res, list) else [res]
    bad = sorted(x["id"] for x in res if x.get("error"))
    other = [x for x in res if x.get("error") and not re.search(r"(?i)syntax|token|keyword|reserved|identifier", x["error"])]
    if other:
        print(f"!! {len(other)} probe(s) failed for another reason (kept as reserved, check): "
              + "; ".join(f"{x['id']}: {x['error'][:80]}" for x in other[:5]), flush=True)
    clash = sorted(set(bad) & used)
    OUT.write_text("# words the engine refuses as DAX VAR names - generated by tools/sync_dax_reserved.py; used by model_gate C6\n"
                   + "\n".join(bad) + "\n", encoding="utf-8")
    print(f"{len(bad)} reserved of {len(cand)} -> {OUT.relative_to(ROOT)}"
          + (f"; !! used as VAR names in dist/: {', '.join(clash)}" if clash else "; no VAR name of the model is reserved"), flush=True)


if __name__ == "__main__":
    main()
