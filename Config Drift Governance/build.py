"""build.py -- ONE command to (re)generate the frontend data from Config report/.

WHAT IT DOES
------------
Runs the offline backend pipeline in dependency order. Each stage reads the COE
export (Config report/data.xlsx) + the CFG-RFC register and (re)writes the
frontend data files under UIUX/assets/*.js using a safe .cache/ build directory
with manifest logging, build status tracking, and stage timeouts.

    python build.py                 # rebuild all frontend assets (offline)
    python build.py --stop-on-error # fail fast on the first broken stage
    python build.py --graph         # additionally rebuild the Neo4j graph
    python build.py --clean         # clean cache folder before build
    python build.py --list          # just print the stages and exit

RULES honoured: timestamped heartbeat logs; no silent failure (every stage's
exit code + stderr tail is logged and a non-zero overall exit is returned if any
stage failed); each stage has a timeout so the build never hangs forever.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import os
import shutil
import subprocess
import sys
import time

HERE = os.path.dirname(os.path.abspath(__file__))
BACKEND = os.path.join(HERE, "backend")
PY = sys.executable
STAGE_TIMEOUT = int(os.environ.get("BUILD_STAGE_TIMEOUT", "900"))  # seconds

CACHE_DIR = os.path.join(HERE, ".cache", "build")
ASSETS_DIR = os.path.join(HERE, "UIUX", "assets")
BUILD_STATUS_JS = os.path.join(ASSETS_DIR, "build-status.js")

# Offline stages, in dependency order. (script, args, human label)
OFFLINE_STAGES = [
    ("xlsx_to_deviations_csv.py", [], "Flatten data.xlsx -> all_sites_deviations.csv"),
    ("cross_site_exceptions.py", [], "Cross-site inconsistencies CSV"),
    ("export_cross_site_ui.py", [], "assets/cross-site.js"),
    ("tag_potential_exceptions.py", [], "assets/potential-exceptions.js"),
    ("build_exception_ledger.py", [], "assets/exception-ledger.js"),
    ("build_change_capture.py", [], "assets/change-capture.js"),
    ("discover_missing_cfg.py", [], "assets/discovered-cfg.js"),
    ("explain_config_values.py", [], "assets/config-meanings.js"),
    ("site_exception_report.py", [], "assets/site-exception-report.js"),
    ("export_drift_ui.py", [], "assets/drift-actions.js"),
]

# Graph stage (opt-in): needs Neo4j reachable at NEO4J_URI.
GRAPH_STAGE = ("build_graph.py", [], "Neo4j knowledge graph + snapshot (needs Neo4j)")


def log(msg: str) -> None:
    print(f"[{time.strftime('%H:%M:%S')}] {msg}", flush=True)


def run_stage(script: str, args: list[str], label: str) -> tuple[str, float, str]:
    """Run one stage. Returns (status, seconds, tail). Never raises for a stage
    failure -- it is logged and reported so the summary is complete."""
    path = os.path.join(BACKEND, script)
    if not os.path.isfile(path):
        log(f"SKIP  {script:32s} (not found)")
        return ("MISSING", 0.0, f"{script} not found in backend/")
    log(f"START {script:32s} -> {label}")
    t0 = time.time()
    try:
        proc = subprocess.run(
            [PY, path, *args],
            cwd=BACKEND,                 # so `import paths` resolves
            capture_output=True, text=True,
            timeout=STAGE_TIMEOUT,
        )
    except subprocess.TimeoutExpired:
        dt = time.time() - t0
        log(f"FAIL  {script:32s} TIMEOUT after {dt:.0f}s")
        return ("TIMEOUT", dt, f"timed out after {STAGE_TIMEOUT}s")
    except OSError as exc:               # log type+message, keep going
        dt = time.time() - t0
        log(f"FAIL  {script:32s} {type(exc).__name__}: {exc}")
        return ("ERROR", dt, f"{type(exc).__name__}: {exc}")
    dt = time.time() - t0
    if proc.returncode == 0:
        log(f"OK    {script:32s} {dt:.1f}s")
        return ("OK", dt, "")
    tail = (proc.stderr or proc.stdout or "").strip().splitlines()[-8:]
    log(f"FAIL  {script:32s} exit {proc.returncode} ({dt:.1f}s)")
    for line in tail:
        log(f"      | {line}")
    return (f"EXIT {proc.returncode}", dt, "\n".join(tail))


def compute_file_hash(path: str) -> str:
    """Compute sha256 hash of a file for cache freshness checking."""
    if not os.path.isfile(path):
        return ""
    h = hashlib.sha256()
    with open(path, "rb") as f:
        while chunk := f.read(65536):
            h.update(chunk)
    return h.hexdigest()


def write_build_status(ok: bool, stages_run: list[dict], error_msg: str = "") -> None:
    """Write build metadata into UIUX/assets/build-status.js for UI freshness indicator."""
    os.makedirs(ASSETS_DIR, exist_ok=True)
    status_data = {
        "ok": ok,
        "timestamp": time.strftime("%Y-%m-%d %H:%M:%S"),
        "stages": stages_run,
        "error": error_msg,
    }
    content = f"/* AUTO-GENERATED by build.py -- do not edit directly */\nwindow.WHS_BUILD = {json.dumps(status_data, indent=2)};\n"
    with open(BUILD_STATUS_JS, "w", encoding="utf-8") as f:
        f.write(content)


def main() -> int:
    ap = argparse.ArgumentParser(description="Rebuild the Config Drift frontend data with cache support")
    ap.add_argument("--graph", action="store_true",
                    help="also rebuild the Neo4j graph (needs Neo4j + NEO4J_* env)")
    ap.add_argument("--stop-on-error", action="store_true",
                    help="abort at the first failing stage")
    ap.add_argument("--clean", action="store_true",
                    help="clean the .cache/build directory before running")
    ap.add_argument("--list", action="store_true", help="print the stages and exit")
    a = ap.parse_args()

    stages = list(OFFLINE_STAGES) + ([GRAPH_STAGE] if a.graph else [])

    if a.list:
        log("Stages:")
        for i, (s, _, lbl) in enumerate(stages, 1):
            print(f"  {i:2d}. {s:32s} {lbl}")
        return 0

    # Ensure cache directory
    os.makedirs(CACHE_DIR, exist_ok=True)
    if a.clean:
        log(f"Cleaning cache folder: {CACHE_DIR}")
        for item in os.listdir(CACHE_DIR):
            item_path = os.path.join(CACHE_DIR, item)
            if os.path.isdir(item_path):
                shutil.rmtree(item_path)
            else:
                os.remove(item_path)

    log(f"Config Drift build starting - {len(stages)} stage(s), backend={BACKEND}, cache={CACHE_DIR}")
    # fail loudly up front if the data folder is missing
    data_dir = os.path.join(HERE, "Config report")
    if not os.path.isdir(data_dir):
        log(f"ABORT data folder not found: {data_dir}")
        log("      Set WHS_WORKSPACE in .env or place 'Config report/' beside build.py.")
        write_build_status(False, [], f"Data folder missing: {data_dir}")
        return 2

    results = []
    stages_log = []
    failed = 0
    for script, args, label in stages:
        status, dt, tail = run_stage(script, args, label)
        results.append((script, status, dt))
        stages_log.append({"script": script, "status": status, "duration_sec": round(dt, 2), "error": tail})
        if status != "OK":
            failed += 1
            if a.stop_on_error:
                log("Stopping (--stop-on-error).")
                break

    # Record manifest in cache
    manifest = {
        "timestamp": time.time(),
        "date": time.strftime("%Y-%m-%d %H:%M:%S"),
        "results": stages_log,
        "input_hashes": {
            "data.xlsx": compute_file_hash(os.path.join(data_dir, "data.xlsx")),
            "Configuration_RFC.csv": compute_file_hash(os.path.join(data_dir, "Configuration_RFC.csv")),
        }
    }
    with open(os.path.join(CACHE_DIR, "manifest.json"), "w", encoding="utf-8") as f:
        json.dump(manifest, f, indent=2)

    log("-" * 60)
    log("Summary:")
    for script, status, dt in results:
        mark = "OK " if status == "OK" else "XX "
        log(f"  {mark} {script:32s} {status:>10s}  {dt:5.1f}s")

    write_build_status(failed == 0, stages_log, f"{failed} stages failed" if failed else "")

    if failed:
        log(f"DONE with {failed} failed stage(s). See logs above.")
        return 1
    log("DONE - all stages OK. Open UIUX/index.html to view the refreshed UI.")
    return 0


if __name__ == "__main__":
    try:
        raise SystemExit(main())
    except KeyboardInterrupt:
        log("Interrupted by user.")
        raise SystemExit(130)
