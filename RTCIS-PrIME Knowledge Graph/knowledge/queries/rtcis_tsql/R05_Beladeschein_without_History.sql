-- R05 Beladeschein without history (RTCIS). T-SQL transliteration of the SYS_get_RTCIS Oracle text.
-- Param: @Ladungsnummer (rcphdr.BOLNUM). The original DECODE has a quoting bug ("DE20,RH.RCVSIT"): kept as-is.
WITH h AS (
    SELECT RH.RRNUMB, RH.RECTYP, RH.BOLNUM, RH.DELVID,
           CASE RH.RCVSIT WHEN '0' THEN 'DE07' WHEN '1' THEN 'DE08' WHEN '2' THEN 'DE09' WHEN '3' THEN 'DE20,RH.RCVSIT' END AS DC,
           RH.VNDCOD, TR.APTDAT, TR.TRLNUM, TL.LOCATN, TN.TRKNAM, TR.ASGDAT
    FROM [EUSKIRCHEN_simp].live3.RCPHDR RH
    JOIN [EUSKIRCHEN_simp].live3.TRUKIO TR ON RH.RRNUMB = TR.RRNUMB
    JOIN [EUSKIRCHEN_simp].live3.TRAILER TL ON TR.TRLNUM = TL.TRLNUM AND TR.TRKLIN = TL.TRKLIN
    JOIN [EUSKIRCHEN_simp].live3.TRKLIN TN ON TL.TRKLIN = TN.TRKLIN
    WHERE RH.BOLNUM = @Ladungsnummer
), sq1 AS (
    SELECT DISTINCT h.RRNUMB, h.RECTYP, h.BOLNUM, h.DELVID, h.DC, h.VNDCOD, '0' AS IT, '0' AS PO, h.APTDAT, h.TRLNUM, h.LOCATN, h.TRKNAM, h.ASGDAT
    FROM h WHERE h.RRNUMB NOT IN (SELECT RRNUMB FROM [EUSKIRCHEN_simp].live3.RCPEXP)
    UNION
    SELECT DISTINCT h.RRNUMB, h.RECTYP, h.BOLNUM, h.DELVID, h.DC, h.VNDCOD, RE.ITMCOD, RE.PONUMB, h.APTDAT, h.TRLNUM, h.LOCATN, h.TRKNAM, h.ASGDAT
    FROM h JOIN [EUSKIRCHEN_simp].live3.RCPEXP RE ON h.RRNUMB = RE.RRNUMB
)
SELECT sq1.RRNUMB, sq1.RECTYP, sq1.BOLNUM AS BN, sq1.DELVID AS IB, sq1.DC, sq1.VNDCOD, sq1.IT, sq1.PO,
       FORMAT(sq1.APTDAT, 'dd.MM.yyyy HH:mm:ss') AS APTDAT, sq1.TRLNUM, sq1.LOCATN, sq1.TRKNAM,
       FORMAT(sq1.ASGDAT, 'dd.MM.yyyy HH:mm:ss') AS ASGDAT
FROM sq1;
