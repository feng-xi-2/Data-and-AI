"""Static snapshot of the validated graph for the WHS GenAI UI (config-drift-governance/UIUX), same pattern as its own
graph-snapshot.js: the page works with no database connection.

    python export_ui_snapshot.py [--ui <UIUX folder>]   -> <UIUX>/assets/rtcis-prime-graph.js  (and ui/rtcis-prime-graph.js in the kit)
"""
import argparse
import json
import os
import shutil
from collections import Counter, defaultdict

KIT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
B = os.path.join(KIT, "benchmark")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--ui", default=os.environ.get("KG_UI_DIR", ""))
    a = ap.parse_args()
    nodes = json.load(open(os.path.join(KIT, "relationships", "nodes.json"), encoding="utf-8"))
    edges = json.load(open(os.path.join(KIT, "relationships", "edges.json"), encoding="utf-8"))
    mv = json.load(open(os.path.join(B, "mapping_validation.json"), encoding="utf-8")) if os.path.exists(os.path.join(B, "mapping_validation.json")) \
        else {"summary": json.load(open(os.path.join(B, "mapping_validation_summary.json"), encoding="utf-8")), "mappings": graphio.load("mappings", B)}
    N = {n["id"]: n for n in nodes}
    sites = defaultdict(list)
    for e in edges:
        if e["label"] == "EXISTS_AT":
            sites[e["src"]].append(N[e["dst"]]["name"])
    tables = [[n["platform"], n["name"], n.get("theme", ""), (n.get("description") or "")[:140], n.get("n_columns", 0), ", ".join(sites[n["id"]])]
              for n in nodes if n["label"] == "Table"]
    curated, structural_tables, n_struct_cols = [], [], 0
    for e in edges:
        if e["label"] != "MAPS_TO":
            continue
        s, d = N[e["src"]], N[e["dst"]]
        name = lambda x: f"{x['table']}.{x['name']}" if x["label"] == "Column" else x["name"]  # noqa: E731
        row = [s["platform"], name(s), d["platform"], name(d), e.get("value_verdict", ""), e.get("sources", e.get("tag", "")),
               e.get("type_check", ""), e.get("conflict", ""), e.get("notes", "")[:160]]
        if e.get("kind") == "structural":
            if s["label"] == "Table":
                structural_tables.append(row)
            else:
                n_struct_cols += 1
        else:
            curated.append(row)
    rejected = [[m["src"][0], ".".join(x for x in m["src"][1:] if x), m["dst"][0], ".".join(x for x in m["dst"][1:] if x),
                 "; ".join(m["sources"]), m["checks"]["V1"][6:]] for m in mv["mappings"] if m["checks"]["V1"] != "PASS"]
    templates = [[n["qid"], n["side"], n.get("title", ""), n.get("intent", ""), n.get("grade", ""), n.get("params", ""), n.get("validated_runs", "")]
                 for n in nodes if n["label"] == "Query"]
    bench = json.load(open(os.path.join(B, "results.json"), encoding="utf-8")) if os.path.exists(os.path.join(B, "results.json")) else {}
    load = json.load(open(os.path.join(B, "cosmos_load_rtcis_prime.json"), encoding="utf-8")) if os.path.exists(os.path.join(B, "cosmos_load_rtcis_prime.json")) else {}
    snap = {"generatedAt": __import__("time").strftime("%Y-%m-%d %H:%M"),
            "counts": {"nodes": dict(Counter(n["label"] for n in nodes)), "edges": dict(Counter(e["label"] for e in edges)),
                       "tables_by_engine": dict(Counter(n["platform"] for n in nodes if n["label"] == "Table")),
                       "columns_by_engine": dict(Counter(n["platform"] for n in nodes if n["label"] == "Column")),
                       "structural_column_maps": n_struct_cols},
            "validation": mv["summary"], "tables": tables, "curated": curated, "structural_tables": structural_tables,
            "rejected": rejected, "templates": templates,
            "benchmark": {k: bench.get(k) for k in ("run_at", "T1", "T2")} | ({"T3": bench["T3"]["stats"]} if "T3" in bench else {}),
            "nl": [{"q": x["question"], "gremlin": x["gremlin"], "n": x.get("n"), "answer": x.get("answer", [])[:5]} for x in bench.get("NL", [])],
            "cosmos": {k: load.get(k) for k in ("db", "graph", "loaded_at", "vertices", "edges")}}
    js = "/* AUTO-GENERATED by export_ui_snapshot.py - validated RTCIS / PrIME 2014 / PrIME 2022 graph. */\nwindow.RP_KG = " + \
         json.dumps(snap, ensure_ascii=False) + ";\n"
    os.makedirs(os.path.join(KIT, "ui"), exist_ok=True)
    open(os.path.join(KIT, "ui", "rtcis-prime-graph.js"), "w", encoding="utf-8").write(js)
    if a.ui:
        open(os.path.join(a.ui, "assets", "rtcis-prime-graph.js"), "w", encoding="utf-8").write(js)
        shutil.copy(os.path.join(KIT, "ui", "rtcis-prime-graph.html"), os.path.join(a.ui, "rtcis-prime-graph.html"))
    print(f"snapshot {len(js) / 1e6:.2f} MB: {len(tables)} tables, {len(curated)} curated + {len(structural_tables)} structural table maps, "
          f"{len(rejected)} rejected, {len(templates)} templates" + (f"; copied to {a.ui}" if a.ui else ""))


if __name__ == "__main__":
    main()
