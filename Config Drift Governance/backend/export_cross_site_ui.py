"""export_cross_site_ui — build a no-build JS data file for the Cross-Site Exceptions view.

Reads cross_site_exception_inconsistencies.csv (produced by cross_site_exceptions.py) and
writes UIUX/assets/cross-site.js which sets window.WHS_XSITE for the static graph page.

Each record = one deviation identity that is ACCEPTED at >=1 site but OPEN (penalised) at
others — i.e. a site scored down for something a peer already governs as an allowed variation.

No network, no build step. Follows workspace rules: timestamped logs; no silent failure.
"""
from __future__ import annotations

import argparse
import csv
import datetime
import json
import os

from paths import WORKSPACE as ONEDRIVE  # portable workspace root (see paths.py)
DEFAULT_IN = os.path.join(ONEDRIVE, "Config report", "cross_site_exception_inconsistencies.csv")
OUT_JS = os.path.join(ONEDRIVE, "UIUX", "assets", "cross-site.js")


def log(msg: str) -> None:
    print(f"[{datetime.datetime.now():%H:%M:%S}] {msg}", flush=True)


def _split(s: str) -> list[str]:
    return [x.strip() for x in (s or "").split(",") if x.strip()]


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--in", dest="inp", default=DEFAULT_IN)
    args = ap.parse_args()
    if not os.path.exists(args.inp):
        log(f"ERROR input not found: {args.inp}")
        raise SystemExit(2)

    log(f"reading {args.inp}")
    try:
        with open(args.inp, encoding="utf-8-sig", newline="") as fh:
            rows = list(csv.DictReader(fh))
    except Exception as e:
        log(f"ERROR failed to read: {type(e).__name__}: {e}")
        raise

    records = []
    total_penalised = 0
    with_cfg = 0
    for r in rows:
        accepted = _split(r.get("Accepted sites", ""))
        opens = _split(r.get("Open sites (penalised)", ""))
        cfgs = _split(r.get("CFG code(s)", ""))
        total_penalised += len(opens)
        if cfgs:
            with_cfg += 1
        records.append({
            "section": (r.get("Configuration Section") or "").strip(),
            "element": (r.get("Configuration Element") or "").strip(),
            "attrId": (r.get("Attribute ID") or "").strip(),
            "attr": (r.get("Attribute Name (GUI)") or "").strip(),
            "type": (r.get("Deviation Type") or "").strip(),
            "a": (r.get("A value") or "").strip(),
            "r": (r.get("R value") or "").strip(),
            "nAccepted": int(r.get("# Accepted sites") or 0),
            "nOpen": int(r.get("# Open (penalised) sites") or 0),
            "cfg": cfgs,
            "accepted": accepted,
            "open": opens,
            "openSev": (r.get("Open severities") or "").strip(),
        })

    # already sorted by penalised desc in the CSV, but be safe
    records.sort(key=lambda x: (-x["nOpen"], -x["nAccepted"]))

    payload = {
        "generatedAt": datetime.datetime.now().isoformat(timespec="seconds"),
        "source": os.path.basename(args.inp),
        "totals": {
            "identities": len(records),
            "penalisedFindings": total_penalised,
            "withCfg": with_cfg,
        },
        "records": records,
    }

    header = ("/* AUTO-GENERATED by export_cross_site_ui.py — do not edit by hand.\n"
              f"   Source: {payload['source']} · {payload['generatedAt']} */\n"
              "window.WHS_XSITE = ")
    try:
        os.makedirs(os.path.dirname(OUT_JS), exist_ok=True)
        with open(OUT_JS, "w", encoding="utf-8") as fh:
            fh.write(header)
            json.dump(payload, fh, ensure_ascii=False, indent=1)
            fh.write(";\n")
    except Exception as e:
        log(f"ERROR failed to write {OUT_JS}: {type(e).__name__}: {e}")
        raise
    log(f"DONE wrote {OUT_JS}")
    log(f"  {len(records)} inconsistent identities · {total_penalised} penalised findings · {with_cfg} CFG-backed")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
