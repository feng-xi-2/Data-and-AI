"""Export real graph views from Cosmos (through the running kg_api.py) for the offline fallback of the knowledge-graph
tab, and copy the tab script into the UI.     python tools/export_ui_views.py [UIUX_DIR]"""
import json
import os
import shutil
import sys
import time
import urllib.parse
import urllib.request
from collections import Counter

KIT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
API = os.environ.get("KG_API", "http://127.0.0.1:8738")
VIEWS = [("versions", t) for t in ("invlod", "locmst", "prtmst", "pckwrk_dtl", "shipment", "rcvlin", "unitld", "itmmst")] \
    + [("query", f"R{n:02d}") for n in range(1, 18)] \
    + [("sdc", m) for m in ("01", "02", "03", "04", "05", "07", "08", "10", "PMC-03.02.01", "PMC-05.02.01", "PMC-02.01.01")] \
    + [("domain", d) for d in ("inventory", "receiving", "picking", "shipment", "location", "counting", "work", "trailer")] \
    + [("issues", ""), ("rules", "")]


def main():
    sys.path.insert(0, os.path.dirname(__file__))
    import graphio
    out, bad = {}, []
    for view, key in VIEWS:
        url = f"{API}/rp/graph?" + urllib.parse.urlencode({"view": view, "key": key})
        g = json.load(urllib.request.urlopen(url, timeout=170))
        ids = {n["id"] for n in g["nodes"]}
        if not g["nodes"] or any(e["src"] not in ids or e["dst"] not in ids for e in g["edges"]):
            bad.append(f"{view}:{key}")
            continue
        out[f"{view}:{key}"] = g
        print(f"{view}:{key}", len(g["nodes"]), len(g["edges"]), flush=True)
    nodes, edges = graphio.load("nodes"), graphio.load("edges")
    schema = json.load(urllib.request.urlopen(f"{API}/rp/schema", timeout=170))
    sample = json.load(urllib.request.urlopen(f"{API}/rp/sample?label=Table%3APrIME2022&limit=40", timeout=170))
    snap = {"generatedAt": time.strftime("%Y-%m-%d %H:%M"), "source": "Cosmos DB whs_kg/rtcis_prime via kg_api.py",
            "counts": {"nodes": dict(Counter(n["label"] for n in nodes)), "edges": dict(Counter(e["label"] for e in edges))},
            "schema": schema, "samples": {"ontology": sample}, "views": out}
    js = "/* AUTO-GENERATED by export_ui_views.py - real views read from Cosmos DB. */\nwindow.RP_VIEWS = " + json.dumps(snap, ensure_ascii=False) + ";\n"
    dst = os.path.join(KIT, "ui", "rtcis-prime-views.js")
    open(dst, "w", encoding="utf-8").write(js)
    ui = sys.argv[1] if len(sys.argv) > 1 else os.environ.get("KG_UIUX_DIR", "")
    if ui:
        shutil.copy(dst, os.path.join(ui, "assets", "rtcis-prime-views.js"))
        shutil.copy(os.path.join(KIT, "ui", "rtcis-prime-tab.js"), os.path.join(ui, "assets", "rtcis-prime-tab.js"))
    print(f"{len(out)} views, {len(js) // 1024} KB; empty/dangling (skipped): {bad}")


if __name__ == "__main__":
    main()
